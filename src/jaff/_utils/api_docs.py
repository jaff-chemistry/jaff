# ABOUTME: Generates the API reference pages and their nav from the numpydoc docstrings
# ABOUTME: (via griffe); run by CI before building the docs site.
"""Generate the API reference pages and their nav from the docstrings.

The pages follow JAFF's API page design: a page per documented package (tables
of its classes, functions, modules and exceptions), a page per class (its
constructor, attributes and methods) and a page per public method or property
(signature, parameters, returns, raises, examples).  The content is read from
the numpydoc docstrings with griffe, so the docstrings are the only source.

The pages are not committed (CI builds them before the site); the nav is,
so a change of exports shows in review.

For each package of :data:`PACKAGES` and module of :data:`CONFIG_MODULES`,
its ``__all__`` decides what is documented; the config modules are listed on,
and nested under, the ``jaff.config`` page.  The pages go under ``docs/reference/`` and the nav between
:data:`NAV_BEGIN` and :data:`NAV_END` in ``zensical.toml``; regenerate both
after changing a docstring or an export with::

    python -m jaff._utils.api_docs
"""

from __future__ import annotations

import importlib
import inspect
import shutil
from functools import lru_cache
from pathlib import Path
from typing import Any, Dict, List, Tuple

import griffe

from ..config import SRC_DIR
from ..config.base import _markdown

DOCS_DIR: Path = SRC_DIR.parent / "docs"
ZENSICAL_TOML: Path = SRC_DIR.parent / "zensical.toml"

#: Documented packages and their nav titles: the only hand-kept list.
PACKAGES: Dict[str, str] = {
    "jaff.core": "Core",
    "jaff.physics": "Physics",
    "jaff.codegen": "Code generation",
    "jaff.drivers": "Drivers",
    "jaff.plotting": "Plotting",
    "jaff.config": "Configuration",
    "jaff.errors": "Errors",
}

#: Modules holding config models (pages under ``reference/config/<title>/``)
#: and their nav titles.
CONFIG_MODULES: Dict[str, str] = {
    "jaff.config.base": "Base",
    "jaff.config.loader": "Loader",
    "jaff.core.network.config": "Network",
    "jaff.core.reaction.config": "Reactions",
    "jaff.physics.photo_reactions.config": "Radiation",
    "jaff.physics.photo_reactions.shielding.config": "Shielding",
    "jaff.physics.dust.config": "Dust",
    "jaff.physics.thermodynamics.config": "Thermodynamics",
    "jaff.physics.thermodynamics.eos.config": "EOS",
    "jaff.cli.jaffgen.config": "jaffgen",
}

NAV_BEGIN = "# BEGIN generated API nav (python -m jaff._utils.api_docs)"
NAV_END = "# END generated API nav"

_ROOT = "reference"
_GENERATED = "<!-- Generated by `python -m jaff._utils.api_docs`; do not edit. -->"


# ----------------------------------------------------------------------
# What is documented
# ----------------------------------------------------------------------


@lru_cache(maxsize=1)
def _griffe_root() -> griffe.Object | griffe.Alias:
    """The ``jaff`` package as griffe reads it (numpydoc docstrings)."""
    return griffe.load(
        "jaff",
        search_paths=[str(SRC_DIR)],
        docstring_parser="numpy",
        resolve_aliases=False,
    )


def _griffe(path: str) -> Any:
    """The griffe object of a dotted ``jaff.…`` path."""
    return _griffe_root()[path.removeprefix("jaff.")]


class _Package:
    """A documented package's exports, sorted by kind."""

    def __init__(self, name: str, title: str, folder: str, children: List[_Package]):
        self.name = name
        self.title = title
        self.folder = folder
        #: Config modules nested under this package (``jaff.config`` only).
        self.children = children
        module = importlib.import_module(name)
        self.module = module
        self.classes: List[Tuple[str, str]] = []
        self.functions: List[Tuple[str, str]] = []
        self.modules: List[Tuple[str, str]] = []
        self.exceptions: List[Tuple[str, str]] = []
        self.constants: List[Tuple[str, str]] = []
        defined = {
            obj.__module__
            for obj in (getattr(module, n) for n in getattr(module, "__all__", []))
            if inspect.isclass(obj) or inspect.isfunction(obj)
        }
        for name_ in getattr(module, "__all__", []):
            obj = getattr(module, name_)
            if inspect.ismodule(obj):
                if not hasattr(obj, "__path__") and obj.__name__ not in defined:
                    self.modules.append((name_, obj.__name__))
            elif inspect.isclass(obj):
                path = f"{obj.__module__}.{obj.__qualname__}"
                kind = self.exceptions if issubclass(obj, BaseException) else self.classes
                kind.append((name_, path))
            elif inspect.isfunction(obj):
                self.functions.append((name_, f"{obj.__module__}.{obj.__qualname__}"))
            else:
                self.constants.append((name_, f"{module.__name__}.{name_}"))


def _packages() -> List[_Package]:
    config = f"{_ROOT}/config"
    children = [
        _Package(name, title, f"{config}/{title.lower()}", [])
        for name, title in CONFIG_MODULES.items()
    ]

    return [
        _Package(
            name,
            title,
            f"{_ROOT}/{name.split('.')[-1]}",
            children if name == "jaff.config" else [],
        )
        for name, title in PACKAGES.items()
    ]


def _with_children(packages: List[_Package]) -> List[_Package]:
    return [p for package in packages for p in (package, *package.children)]


# ----------------------------------------------------------------------
# Pages
# ----------------------------------------------------------------------


def api_pages() -> Dict[str, str]:
    """Return every API page, keyed by its path relative to ``docs/``."""
    packages = _packages()
    pages = {f"{_ROOT}/index.md": _root_page(packages)}
    for package in _with_children(packages):
        pages[f"{package.folder}/index.md"] = _package_page(package)
        for name, path in package.classes:
            folder = f"{package.folder}/{name.lower()}"
            cls = _griffe(path)
            pages[f"{folder}/index.md"] = _class_page(name, f"{package.name}.{name}", cls)
            for member_name, member in _public_members(cls):
                pages[f"{folder}/{member_name}.md"] = _member_page(
                    name, member_name, member
                )
        for name, path in package.functions:
            pages[f"{package.folder}/{name}.md"] = _function_page(name, _griffe(path))
        for name, path in package.modules:
            pages[f"{package.folder}/{name}/index.md"] = _module_page(name, _griffe(path))

    return pages


def api_nav() -> str:
    """Return the API section of the ``zensical.toml`` nav, markers included."""
    lines = [NAV_BEGIN, '  { "API Reference" = [', f'    "{_ROOT}/index.md",']
    for package in _packages():
        lines += _package_nav(package, "    ", f"{package.name.split('.')[-1]}.")

    lines += ["  ] },", f"  {NAV_END}"]

    return "\n".join(lines)


def _package_nav(package: _Package, indent: str, prefix: str) -> List[str]:
    """Nav lines of *package*: its pages, then its classes' and children's groups."""
    inner = indent + "  "
    lines = [f'{indent}{{ "{package.title}" = [', f'{inner}"{package.folder}/index.md",']
    for name, path in package.classes:
        folder = f"{package.folder}/{name.lower()}"
        members = [f'"{folder}/{m}.md"' for m, _ in _public_members(_griffe(path))]
        lines.append(f'{inner}{{ "{prefix}{name}" = [')
        lines.append(f'{inner}  "{folder}/index.md",')
        lines += [f"{inner}  {member}," for member in members]
        lines.append(f"{inner}] }},")
    lines += [f'{inner}"{package.folder}/{name}.md",' for name, _ in package.functions]
    lines += [
        f'{inner}"{package.folder}/{name}/index.md",' for name, _ in package.modules
    ]
    for child in package.children:
        lines += _package_nav(child, inner, "")

    lines.append(f"{indent}] }},")

    return lines


def _front_matter(*tags: str) -> str:
    return "---\ntags:\n" + "".join(f"    - {tag}\n" for tag in tags) + "---\n"


def _root_page(packages: List[_Package]) -> str:
    rows = [
        f"| [`{p.name}`]({p.name.split('.')[-1]}/index.md) | {_summary(p.module.__doc__)} |"
        for p in packages
    ]
    table = "| Package | Description |\n| --- | --- |\n" + "\n".join(rows)

    return (
        f"{_front_matter('Api')}\n# API Reference\n\n{_GENERATED}\n\n"
        f"Generated from the docstrings of JAFF's public packages.\n\n{table}\n"
    )


def _package_page(package: _Package) -> str:
    doc = _griffe(package.name).docstring
    parts = [
        f"{_front_matter('Api')}\n# {package.name}\n",
        _GENERATED + "\n",
        _sections(doc, skip=()) if doc else "",
    ]
    tables = [
        (
            "Classes",
            "Class",
            [(n, f"{n.lower()}/index.md", p) for n, p in package.classes],
        ),
        ("Functions", "Function", [(n, f"{n}.md", p) for n, p in package.functions]),
        ("Modules", "Module", [(n, f"{n}/index.md", p) for n, p in package.modules]),
    ]
    if package.children:
        rows = [
            (c.name, f"{c.folder.removeprefix(package.folder + '/')}/index.md", c.name)
            for c in package.children
        ]
        tables.append(("Config Modules", "Module", rows))
    for title, column, rows in tables:
        if rows:
            body = "\n".join(
                f"| [`{n}`]({link}) | {_summary(_doc_text(_griffe(p)))} |"
                for n, link, p in rows
            )
            parts.append(
                f"## {title}\n\n| {column} | Description |\n| --- | --- |\n{body}\n"
            )

    if package.exceptions:
        body = "\n".join(
            f"| `{n}` | {_summary(_doc_text(_griffe(p)))} |"
            for n, p in package.exceptions
        )
        parts.append(
            f"## Exceptions\n\n| Exception | Description |\n| --- | --- |\n{body}\n"
        )

    if package.constants:
        body = "\n".join(_constant_row(n, p) for n, p in package.constants)
        parts.append(f"## Constants\n\n| Name | Description |\n| --- | --- |\n{body}\n")

    return "\n".join(part for part in parts if part)


#: Class docstring sections shown after the constructor and attributes.
_CLASS_SECTIONS_BELOW = ("admonition", "examples")


def _class_page(name: str, public_path: str, cls: Any) -> str:
    parts = [
        f"{_front_matter('Api', name)}\n# {name}\n",
        f"`{public_path}`\n",
        _GENERATED + "\n",
        _sections(
            cls.docstring, skip=_CLASS_SECTIONS_BELOW + ("attributes", "parameters")
        )
        if cls.docstring
        else "",
    ]
    init = cls.members.get("__init__")
    if init is not None and not init.is_alias:
        constructor = [f"## Constructor\n\n`#!python {name}({_signature(init)})`\n"]
        source = init.docstring or cls.docstring
        if source:
            constructor.append(
                _sections(source, skip=_CLASS_SECTIONS_BELOW + ("text", "attributes"))
            )
        parts.append("\n".join(c for c in constructor if c))

    attributes = _attributes(cls.docstring)
    if attributes:
        rows = "\n".join(
            f"| `{a.name}` | {_code(a.annotation)} | {_cell(a.description)} |"
            for a in attributes
        )
        parts.append(
            f"## Attributes\n\n| Attribute | Type | Description |\n| --- | --- | --- |\n{rows}\n"
        )

    for section in cls.docstring.parsed if cls.docstring else []:
        if section.kind.value == "admonition":
            text = _markdown(section.value.description)
            parts.append(f"## {section.title}\n\n{text}\n")
        elif section.kind.value == "examples":
            body = "\n\n".join(_example(e) for e in section.value)
            parts.append(f"## Examples\n\n{body}\n")

    members = _public_members(cls)
    for title, column, is_property in (
        ("Properties", "Property", True),
        ("Methods", "Method", False),
    ):
        rows = [
            f"| [`{m}`]({m}.md) | {_summary(_doc_text(member))} |"
            for m, member in members
            if ("property" in member.labels) == is_property
        ]
        if rows:
            body = "\n".join(rows)
            parts.append(
                f"## {title}\n\n| {column} | Description |\n| --- | --- |\n{body}\n"
            )

    return "\n".join(part for part in parts if part)


def _member_page(class_name: str, name: str, member: Any) -> str:
    is_property = "property" in member.labels
    signature = (
        f"`#!python {class_name}.{name}`\n\n*property*"
        if is_property
        else f"`#!python {name}({_signature(member)})`"
    )
    body = _sections(member.docstring, skip=()) if member.docstring else ""

    return (
        f"{_front_matter('Api', class_name)}\n# {name}\n\n{signature}\n\n"
        f"{_GENERATED}\n\n{body}"
    ).rstrip() + "\n"


def _function_page(name: str, function: Any) -> str:
    body = _sections(function.docstring, skip=()) if function.docstring else ""

    return (
        f"{_front_matter('Api')}\n# {name}\n\n`#!python {name}({_signature(function)})`\n\n"
        f"{_GENERATED}\n\n{body}"
    ).rstrip() + "\n"


def _module_page(name: str, module: Any) -> str:
    parts = [
        f"{_front_matter('Api')}\n# {name}\n",
        f"`{module.path}`\n",
        _GENERATED + "\n",
        _sections(module.docstring, skip=()) if module.docstring else "",
    ]
    attributes = [
        member
        for member_name, member in module.members.items()
        if not member_name.startswith("_") and not member.is_alias and member.is_attribute
    ]
    if attributes:
        rows = "\n".join(f"| `{a.name}` | {_cell(_doc_text(a))} |" for a in attributes)
        parts.append(f"## Attributes\n\n| Name | Description |\n| --- | --- |\n{rows}\n")

    return "\n".join(part for part in parts if part)


# ----------------------------------------------------------------------
# Docstring sections, in the page design's markdown
# ----------------------------------------------------------------------


def _sections(docstring: Any, skip: Tuple[str, ...]) -> str:
    """Render a parsed docstring's sections, but those in *skip*."""
    out: List[str] = []
    for section in docstring.parsed:
        kind = section.kind.value
        if kind in skip:
            continue

        if kind == "text":
            out.append(_markdown(section.value))
        elif kind in ("parameters", "other parameters"):
            title = "Parameters" if kind == "parameters" else "Other Parameters"
            items = [_parameter(p) for p in section.value]
            out.append(f"**{title}**\n\n" + "\n\n".join(items))
        elif kind in ("returns", "yields", "receives"):
            items = [
                _definition(_italic(_return_type(r)), r.description)
                for r in section.value
            ]
            out.append(f"**{kind.capitalize()}**\n\n" + "\n\n".join(items))
        elif kind in ("raises", "warns"):
            items = [
                _definition(_italic(str(e.annotation)), e.description)
                for e in section.value
            ]
            out.append(f"**{kind.capitalize()}**\n\n" + "\n\n".join(items))
        elif kind == "examples":
            out.append(
                "**Examples**\n\n" + "\n\n".join(_example(e) for e in section.value)
            )
        elif kind == "attributes":
            rows = "\n".join(
                f"| `{a.name}` | {_code(a.annotation)} | {_cell(a.description)} |"
                for a in section.value
            )
            out.append(f"| Attribute | Type | Description |\n| --- | --- | --- |\n{rows}")
        elif kind == "admonition":
            out.append(f"**{section.title}**\n\n{_markdown(section.value.description)}")

    return "\n\n".join(part for part in out if part.strip()) + "\n"


def _parameter(parameter: Any) -> str:
    annotation = str(parameter.annotation) if parameter.annotation else ""
    if parameter.default is not None and "optional" not in annotation:
        annotation = f"{annotation}, optional" if annotation else "optional"

    term = f"**{parameter.name}**" + (f" : {_italic(annotation)}" if annotation else "")

    return _definition(term, parameter.description)


def _return_type(item: Any) -> str:
    annotation = str(item.annotation) if item.annotation else ""
    if item.name and annotation:
        return f"{item.name}: {annotation}"

    return annotation or item.name or ""


def _definition(term: str, description: str) -> str:
    """A definition-list entry: *term*, then ``: description`` (indented lines)."""
    lines = _markdown(description or "").splitlines() or [""]
    body = [f": {lines[0]}"] + [f"    {line}" if line else "" for line in lines[1:]]

    return term + "\n" + "\n".join(body)


def _example(example: Tuple[Any, str]) -> str:
    kind, text = example
    if getattr(kind, "value", kind) == "examples":
        return f"```python\n{text}\n```"

    return _markdown(text)


def _attributes(docstring: Any) -> List[Any]:
    if docstring is None:
        return []

    for section in docstring.parsed:
        if section.kind.value == "attributes":
            return list(section.value)

    return []


def _public_members(cls: Any) -> List[Tuple[str, Any]]:
    """Public methods and properties of a class, in source order."""
    return [
        (name, member)
        for name, member in cls.members.items()
        if not name.startswith("_")
        and not member.is_alias
        and (member.is_function or "property" in member.labels)
    ]


def _doc_text(obj: Any) -> str:
    return obj.docstring.value if getattr(obj, "docstring", None) else ""


def _summary(doc: str | None) -> str:
    """First line of a docstring, as a table cell."""
    lines = inspect.cleandoc(doc or "").splitlines()

    return _cell(lines[0]) if lines else ""


def _constant_row(name: str, path: str) -> str:
    try:
        description = _doc_text(_griffe(path))
    except KeyError:
        description = ""

    return f"| `{name}` | {_cell(description)} |"


def _signature(function: Any) -> str:
    """Parameters of a function as written in a call, without ``self``/``cls``."""
    parts: List[str] = []
    for parameter in function.parameters:
        # self/cls and private (underscore) parameters are not part of the API.
        if parameter.name in ("self", "cls") or parameter.name.startswith("_"):
            continue

        kind = parameter.kind.value
        if kind == "variadic positional":
            parts.append(f"*{parameter.name}")
        elif kind == "variadic keyword":
            parts.append(f"**{parameter.name}")
        elif parameter.default is not None:
            parts.append(f"{parameter.name}={parameter.default}")
        else:
            parts.append(parameter.name)

    return ", ".join(parts)


def _italic(text: str) -> str:
    return f"_{text}_" if text else ""


def _code(annotation: Any) -> str:
    """A type as inline code for a table cell (``|`` escaped)."""
    if not annotation:
        return ""

    escaped = str(annotation).replace("|", "\\|")

    return f"`{escaped}`"


def _cell(text: str) -> str:
    """Text fit for a markdown table cell: one line, pipes escaped."""
    return " ".join(_markdown(text or "").split()).replace("|", "\\|")


def write_api_docs() -> None:
    """Write the API pages and the nav section of ``zensical.toml``.

    ``docs/reference/`` holds generated pages only: it is emptied first, so
    pages of removed exports do not linger.
    """
    shutil.rmtree(DOCS_DIR / _ROOT, ignore_errors=True)
    for relative, text in api_pages().items():
        path = DOCS_DIR / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")

    toml = ZENSICAL_TOML.read_text(encoding="utf-8")
    start, end = toml.index(NAV_BEGIN), toml.index(NAV_END) + len(NAV_END)
    ZENSICAL_TOML.write_text(toml[:start] + api_nav() + toml[end:], encoding="utf-8")


if __name__ == "__main__":
    write_api_docs()
