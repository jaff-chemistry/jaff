# ABOUTME: Generates the configuration reference page (markdown) from the config
# ABOUTME: models (python -m jaff.config.reference)
"""The configuration reference page, generated from the config models.

One section per TOML table of a ``jaffgen.toml`` (a ``jaff.toml`` holds its
``[network]`` part): each key with its type, default and description, the
description being the key's numpydoc ``Attributes`` entry in the model's
docstring (or a base model's).  Tables whose keys depend on their ``type``
(the EOS, the shielding models) get one subsection per type.  The page is
written to :data:`REFERENCE_PAGE` (not committed; CI builds it before the
site); write it before serving the docs locally with:

```bash
python -m jaff.config.reference
```
"""

from __future__ import annotations

import json
from pathlib import Path
from types import NoneType
from typing import Any, Dict, List, Literal, Tuple, get_args, get_origin

from pydantic import BaseModel
from pydantic.fields import FieldInfo

from ._config import SRC_DIR
from .base import attribute_descriptions, field_descriptions
from .loader import _members

#: The generated reference page (gitignored, not committed).
REFERENCE_PAGE: Path = (
    SRC_DIR.parent / "docs" / "user-guide" / "configuration" / "reference.md"
)

#: Placeholder for a serialized reaction in a per-reaction table header.
_SERIALIZED = '"<serialized>"'

_HEADER = """\
---
tags:
    - Configuration
---

# Configuration reference

<!-- Generated by `python -m jaff.config.reference` from the config models; do not edit. -->

Every key of a `jaffgen.toml`; a `jaff.toml` holds the `[network]` tables only.
Keys are optional unless their default reads *required*; *unset* means the key
has no value unless given.  See the [overview](index.md) for how the files,
the command line and Python combine.
"""

_TABLE_HEAD = "| Key | Type | Default | Description |\n| --- | --- | --- | --- |"


def config_reference() -> str:
    """Return the reference page as markdown, one section per TOML table."""
    from ..cli.jaffgen.config import JaffgenConfig
    from ..core.network.config import NetworkConfig

    sections: List[str] = [_HEADER]
    documented: Dict[type, str] = {}
    for name, model in (("jaffgen", JaffgenConfig), ("network", NetworkConfig)):
        _document(model, (name,), None, sections, documented)

    return "\n".join(sections)


def _document(
    model: type[BaseModel],
    path: Tuple[str, ...],
    defaults: BaseModel | None,
    sections: List[str],
    documented: Dict[type, str],
) -> None:
    """Append the section of *model*'s table at *path*, then of its sub-tables.

    *defaults* is the table's default value in its parent, if any: its values
    are the keys' defaults (e.g. the global photo settings).  A table whose
    keys a table already documented holds gets a pointer to it instead.
    """
    header = _table(path)
    covering = next(
        (cls for cls in documented if issubclass(cls, model) and cls is not model), None
    )
    if covering is not None:
        extra = sorted(set(covering.model_fields) - set(model.model_fields))
        sections.append(_same_keys_section(header, documented[covering], extra))
        return

    sharing = _sharing(model, documented)
    if sharing is not None:
        _document_shared(model, path, defaults, sections, documented, *sharing)
        return

    documented[model] = header
    summary, _ = attribute_descriptions(model.__doc__)
    fields = field_descriptions(model)
    sections.append(
        f"## `{header}`\n\n{summary}\n\n"
        + _table_rows(model, fields, path, defaults, skip=())
    )

    for name, field in model.model_fields.items():
        default = getattr(defaults, name) if defaults is not None else field.default
        _document_child(
            name, field, fields.get(name, ""), path, default, sections, documented
        )


def _sharing(
    model: type[BaseModel], documented: Dict[type, str]
) -> Tuple[type[BaseModel], type[BaseModel]] | None:
    """A documented table sharing a base of keys with *model*: ``(its class, base)``.

    E.g. a reaction's own table and ``[network.reactions]`` both derive from the
    settings they share, each adding keys of its own.
    """
    for base in model.__mro__[1:]:
        if not isinstance(base, type) or not issubclass(base, BaseModel):
            continue
        if not base.model_fields or base.__module__.startswith("pydantic"):
            continue
        for cls in documented:
            if cls is not model and issubclass(cls, base):
                return cls, base

    return None


def _document_shared(
    model: type[BaseModel],
    path: Tuple[str, ...],
    defaults: BaseModel | None,
    sections: List[str],
    documented: Dict[type, str],
    other: type[BaseModel],
    base: type[BaseModel],
) -> None:
    """Section of *model*'s table pointing to *other*'s for the keys of *base*, with a
    table of the keys only *model* has (and their sub-tables)."""
    header = _table(path)
    documented[model] = header
    extra = sorted(set(other.model_fields) - set(model.model_fields))
    fields = field_descriptions(model)
    shared = tuple(base.model_fields)
    sections.append(
        _same_keys_section(header, documented[other], extra)
        + "\n"
        + _table_rows(model, fields, path, defaults, skip=shared)
    )
    for name, field in model.model_fields.items():
        if name in shared:
            continue
        default = getattr(defaults, name) if defaults is not None else field.default
        _document_child(
            name, field, fields.get(name, ""), path, default, sections, documented
        )


def _same_keys_section(header: str, base: str, extra: List[str]) -> str:
    """Section of a table holding the keys of the table *base* (but *extra*)."""
    but = f" apart from {', '.join(f'`{key}`' for key in extra)}" if extra else ""

    return (
        f"## `{header}`\n\nSame keys as `{base}`{but}; a key not set here takes "
        f"its value from `{base}`.\n"
    )


def _document_child(
    name: str,
    field: FieldInfo,
    description: str,
    path: Tuple[str, ...],
    default: Any,
    sections: List[str],
    documented: Dict[type, str],
) -> None:
    """Append the sections of the sub-table(s) a field holds, if any."""
    from ..physics.photo_reactions.shielding.config import ShieldingConfig

    members = _members(field.annotation)
    tables = [m for m in members if _is_model(m)]
    dicts = [m for m in members if get_origin(m) is dict]

    if tables == [ShieldingConfig]:
        sections.append(_shielding_section((*path, name), description))
    elif len(tables) > 1:
        sections.append(_variants_section((*path, name), description, tables, default))
    elif tables:
        own = default if isinstance(default, BaseModel) else None
        _document(tables[0], (*path, name), own, sections, documented)
    elif dicts:
        entries = [m for m in _members(get_args(dicts[0])[1]) if _is_model(m)]
        if entries:
            _document(entries[0], (*path, name, _SERIALIZED), None, sections, documented)


def _variants_section(
    path: Tuple[str, ...],
    description: str,
    variants: List[type[BaseModel]],
    default: Any,
) -> str:
    """Section of a table whose ``type`` key selects its model (e.g. the EOS)."""
    parts = [f"## `{_table(path)}`\n\n{description}\n"]
    for variant in variants:
        type_name = variant.model_fields["type"].default
        note = " (the default)" if isinstance(default, variant) else ""
        parts.append(_variant(type_name, note, variant, path))

    return "\n".join(parts)


def _shielding_section(path: Tuple[str, ...], description: str) -> str:
    """Section of a ``shielding`` table: one subsection per shielding plugin."""
    from ..physics.photo_reactions.shielding import shielding_functions
    from ..physics.photo_reactions.shielding.config import ShieldingConfig

    default = ShieldingConfig.model_fields["type"].default
    parts = [
        f"## `{_table(path)}`\n\n{description}  Written as one table, e.g. "
        '`shielding = { type = "leiden", shielded_by = ["self"] }`; its `type` '
        "selects the shielding model and its other keys.\n"
    ]
    for (name, reaction), plugin in sorted(
        shielding_functions().items(), key=lambda item: (item[0][0], item[0][1] or "")
    ):
        note = " (the default)" if name == default else ""
        only = f" — only for `{reaction}`" if reaction is not None else ""
        parts.append(_variant(name, note + only, plugin.config_model(), path))

    return "\n".join(parts)


def _variant(
    type_name: str, note: str, model: type[BaseModel], path: Tuple[str, ...]
) -> str:
    """Subsection of one ``type`` of a type-selected table."""
    summary, _ = attribute_descriptions(model.__doc__)
    fields = field_descriptions(model)
    if not set(model.model_fields) - {"type"}:
        return f'### `type = "{type_name}"`{note}\n\n{summary}\n\nNo other keys.\n'

    rows = _table_rows(model, fields, path, None, skip=("type",))

    return f'### `type = "{type_name}"`{note}\n\n{summary}\n\n{rows}'


def _table_rows(
    model: type[BaseModel],
    fields: Dict[str, str],
    path: Tuple[str, ...],
    defaults: BaseModel | None,
    skip: Tuple[str, ...],
) -> str:
    """The key table of *model*: one row per key but those in *skip*."""
    rows = [
        _row(name, field, fields.get(name, ""), path, defaults)
        for name, field in model.model_fields.items()
        if name not in skip
    ]

    return f"{_TABLE_HEAD}\n" + "\n".join(rows) + "\n"


def _row(
    name: str,
    field: FieldInfo,
    description: str,
    path: Tuple[str, ...],
    defaults: BaseModel | None,
) -> str:
    """Table row of one key; its default taken from *defaults* when given."""
    default = _value(getattr(defaults, name)) if defaults is not None else _default(field)
    see = _sub_table(name, field, path)
    text = f"{description} See `{see}`.".strip() if see else description
    cells = [f"`{name}`", _type(field.annotation), default, text]

    return "| " + " | ".join(cell.replace("|", "\\|") for cell in cells) + " |"


def _sub_table(name: str, field: FieldInfo, path: Tuple[str, ...]) -> str | None:
    """Header of the sub-table a field holds, if it holds one."""
    members = _members(field.annotation)
    if any(_is_model(m) for m in members):
        return _table((*path, name))

    dicts = [m for m in members if get_origin(m) is dict]
    if dicts and any(_is_model(m) for m in _members(get_args(dicts[0])[1])):
        return _table((*path, name, _SERIALIZED))

    return None


def _type(annotation: Any) -> str:
    """Describe a field's type in TOML terms."""
    names = [_type_name(m) for m in _members(annotation) if m is not NoneType]

    return " or ".join(dict.fromkeys(names))


def _type_name(member: Any) -> str:
    """Describe one member of a field's type."""
    origin = get_origin(member)
    if origin is Literal:
        return " or ".join(f"`{json.dumps(value)}`" for value in get_args(member))

    if origin is list:
        return f"array of {_type(get_args(member)[0])}"

    if origin is dict or _is_model(member):
        return "table"

    names = {
        bool: "boolean",
        int: "integer",
        float: "number",
        str: "string",
        Path: "path",
    }

    return names.get(member, getattr(member, "__name__", str(member)))


def _default(field: FieldInfo) -> str:
    """Describe a field's default value."""
    if field.is_required():
        return "required"

    return _value(field.get_default(call_default_factory=True))


def _value(value: Any) -> str:
    """Describe a default value."""
    if value is None:
        return "unset"

    if isinstance(value, BaseModel):
        return "—"

    return f"`{json.dumps(value)}`"


def _is_model(member: Any) -> bool:
    """Whether a type member is a config model (a sub-table)."""
    return isinstance(member, type) and issubclass(member, BaseModel)


def _table(path: Tuple[str, ...]) -> str:
    """TOML table header of a key path."""
    return "[" + ".".join(path) + "]"


def write_reference(path: Path = REFERENCE_PAGE) -> None:
    """Write the reference page to *path*."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(config_reference(), encoding="utf-8")


if __name__ == "__main__":
    write_reference()
