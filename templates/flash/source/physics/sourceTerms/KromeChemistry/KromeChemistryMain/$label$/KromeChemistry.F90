! ABOUTME: Burns the JAFF-generated chemistry in every cell over one FLASH step with
! ABOUTME: DLSODES (analytic Jacobian), then updates the species and the temperature
!!****if* source/physics/sourceTerms/KromeChemistry/KromeChemistryMain/KromeChemistry
!!
!! NAME
!!  KromeChemistry
!!
!! SYNOPSIS
!!  call KromeChemistry(integer :: blockCount,
!!                      integer, dimension(blockCount) :: blockList,
!!                      real :: dt)
!!
!! DESCRIPTION
!!  Converts each cell's mass fractions to number densities, integrates the
!!  generated chemistry (densities and gas temperature) over dt with FLASH's
!!  ODEPACK/DLSODES, converts back and calls the EOS (density, temperature).
!!  Generated by jaffgen.
!!
!!***

subroutine KromeChemistry(blockCount, blockList, dt)

  use KromeChemistry_data
  use chemistry, ONLY : nspecs
  use chemistry_dlsodes, ONLY : fex, jes, neq
  use Timers_interface, ONLY : Timers_start, Timers_stop
  use Grid_interface, ONLY : Grid_getBlkIndexLimits, Grid_getBlkPtr, Grid_releaseBlkPtr
  use Eos_interface, ONLY : Eos_wrapped
  use Driver_interface, ONLY : Driver_abortFlash

  implicit none

#include "constants.h"
#include "Flash.h"
#include "Eos.h"

  integer, intent(in) :: blockCount
  integer, intent(in), dimension(blockCount) :: blockList
  real, intent(in) :: dt

  ! DLSODES settings: stiff, analytic Jacobian columns (MF = 121), scalar tolerances,
  ! optional inputs for the step limit
  integer, parameter :: mf = 121, itol = 1, itask = 1, iopt = 1
  integer, parameter :: lrw = 100 + 20*neq + 6*neq**2, liw = 31 + neq
  real*8 :: rwork(lrw), y(neq), t, rtol(1), atol(1)
  integer :: iwork(liw), istate
  integer :: i, j, k, n, blockID, thisBlock
  integer, dimension(2,MDIM) :: blkLimits, blkLimitsGC
  real :: rho
  real, pointer, dimension(:,:,:,:) :: solnData
  external :: dlsodes

  if (.not. useKromeChemistry) return

  call Timers_start("chemistry")
  rtol = jaff_rtol
  atol = jaff_atol

  do thisBlock = 1, blockCount
     blockID = blockList(thisBlock)
     call Grid_getBlkIndexLimits(blockID, blkLimits, blkLimitsGC)
     call Grid_getBlkPtr(blockID, solnData)

     do k = blkLimits(LOW,KAXIS), blkLimits(HIGH,KAXIS)
        do j = blkLimits(LOW,JAXIS), blkLimits(HIGH,JAXIS)
           do i = blkLimits(LOW,IAXIS), blkLimits(HIGH,IAXIS)
              rho = solnData(DENS_VAR,i,j,k)
              if (rho < krome_density_threshold) cycle

              ! mass fractions -> number densities [cm^-3], then the temperature
              do n = 1, nspecs
                 y(n) = solnData(specieMap(n),i,j,k) * rho / specieMass(n)
              end do
              y(neq) = max(solnData(TEMP_VAR,i,j,k), krome_temp_floor)

              t = 0d0
              rwork = 0d0
              iwork = 0
              iwork(6) = jaff_max_steps
              istate = 1
              call dlsodes(fex, [neq], y, t, dble(dt), itol, rtol, atol, itask, &
                           istate, iopt, rwork, lrw, iwork, liw, jes, mf)
              if (istate < 0) then
                 call Driver_abortFlash("KromeChemistry: DLSODES failed")
              end if

              ! number densities -> mass fractions
              do n = 1, nspecs
                 solnData(specieMap(n),i,j,k) = y(n) * specieMass(n) / rho
              end do
              solnData(TEMP_VAR,i,j,k) = y(neq)
           end do
        end do
     end do

     call Grid_releaseBlkPtr(blockID, solnData)
     call Eos_wrapped(MODE_DENS_TEMP, blkLimits, blockID)
  end do

  call Timers_stop("chemistry")

end subroutine KromeChemistry
