! ABOUTME: Initialises the JAFF-generated KromeChemistry unit: reads the settings and the
! ABOUTME: network parameters (jaff_<name>, all required) and maps species to unk
!!****if* source/physics/sourceTerms/KromeChemistry/KromeChemistryMain/KromeChemistry_init
!!
!! NAME
!!  KromeChemistry_init
!!
!! DESCRIPTION
!!  Reads the unit's runtime parameters, copies the network parameters into the
!!  chemistry module (stopping, named, on any left at its unset default) and maps
!!  every network species to its FLASH unk variable. Generated by jaffgen.
!!
!!***

subroutine KromeChemistry_init()

   use KromeChemistry_data
   use chemistry
   use RuntimeParameters_interface, ONLY : RuntimeParameters_get
   use Simulation_interface, ONLY : Simulation_mapStrToInt
   use Driver_interface, ONLY : Driver_abortFlash

   implicit none

#include "constants.h"
#include "Flash.h"

   ! Local names start with kc_ so that no network parameter (a chemistry module
   ! variable) can clash with them
   real, parameter :: kc_unset = -1.0e300   ! default of every jaff_<name>
   character(len=MAX_STRING_LENGTH) :: kc_missing
   character(len=16) :: kc_names(NSPECIES)
   integer :: kc_n

   call RuntimeParameters_get("useKromeChemistry", useKromeChemistry)
   call RuntimeParameters_get("krome_temp_floor", krome_temp_floor)
   call RuntimeParameters_get("krome_density_threshold", krome_density_threshold)
   call RuntimeParameters_get("jaff_rtol", jaff_rtol)
   call RuntimeParameters_get("jaff_atol", jaff_atol)
   call RuntimeParameters_get("jaff_max_steps", jaff_max_steps)
   call RuntimeParameters_get("jaff_evolve_temperature", evolve_temperature)

   ! The network parameters, read into the chemistry module's variables
   kc_missing = ""
   $$JAFF REPEAT idx, parameter IN parameters { THERMAL { MODE -> dtdt } }
   call RuntimeParameters_get("jaff_$parameter$", $parameter$)
   if ($parameter$ == kc_unset) kc_missing = trim(kc_missing) // " jaff_$parameter$"
   $$JAFF END
   if (len_trim(kc_missing) > 0) then
      call Driver_abortFlash("KromeChemistry: set in flash.par:" // trim(kc_missing))
   end if

   ! unk variable and mass [g] of every species, in network order
   $$JAFF REPEAT idx, specie_with_normalized_sign IN species_with_normalized_sign {
       SIGN { POS -> j  NEG -> k }
   }
   kc_names($idx+1$) = "$specie_with_normalized_sign$"
   $$JAFF END
   $$JAFF REPEAT idx, specie_mass IN specie_masses
   specieMass($idx+1$) = $specie_mass$
   $$JAFF END
   do kc_n = 1, NSPECIES
      call Simulation_mapStrToInt(trim(kc_names(kc_n)), specieMap(kc_n), MAPBLOCK_UNK)
   end do

end subroutine KromeChemistry_init
