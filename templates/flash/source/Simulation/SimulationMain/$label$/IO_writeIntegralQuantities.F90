! ABOUTME: One-zone override of FLASH's integral output: appends the zone's state to
! ABOUTME: sim_outputFile each step (time, T, number densities in network order)
!!****if* source/Simulation/SimulationMain/IO_writeIntegralQuantities
!!
!! NAME
!!  IO_writeIntegralQuantities
!!
!! DESCRIPTION
!!  Writes "# t[s] T[K] <species>" once, then one line per call with the time, the
!!  temperature and every species' number density n_i = X_i rho / m_i [cm^-3] of
!!  the first zone. Generated by jaffgen.
!!
!!***

subroutine IO_writeIntegralQuantities(isFirst, simTime)

  use Simulation_data, ONLY : sim_outputFile, sim_speciesName, sim_unkName, &
       sim_speciesMass
  use Grid_interface, ONLY : Grid_getListOfBlocks, Grid_getBlkIndexLimits, &
       Grid_getBlkPtr, Grid_releaseBlkPtr
  use Simulation_interface, ONLY : Simulation_mapStrToInt
  use Driver_interface, ONLY : Driver_getMype

  implicit none

#include "constants.h"
#include "Flash.h"

  integer, intent(in) :: isFirst
  real, intent(in) :: simTime

  integer :: blkList(MAXBLOCKS), blkCount, myPE, unit, n, unk
  integer, dimension(2,MDIM) :: blkLimits, blkLimitsGC
  real, pointer, dimension(:,:,:,:) :: solnData
  real :: rho, temp, nden(NSPECIES)

  call Driver_getMype(GLOBAL_COMM, myPE)
  if (myPE /= MASTER_PE) return

  call Grid_getListOfBlocks(LEAF, blkList, blkCount)
  call Grid_getBlkIndexLimits(blkList(1), blkLimits, blkLimitsGC)
  call Grid_getBlkPtr(blkList(1), solnData)
  associate (i => blkLimits(LOW,IAXIS), j => blkLimits(LOW,JAXIS), &
             k => blkLimits(LOW,KAXIS))
    rho = solnData(DENS_VAR,i,j,k)
    temp = solnData(TEMP_VAR,i,j,k)
    do n = 1, NSPECIES
       call Simulation_mapStrToInt(trim(sim_unkName(n)), unk, MAPBLOCK_UNK)
       nden(n) = solnData(unk,i,j,k) * rho / sim_speciesMass(n)
    end do
  end associate
  call Grid_releaseBlkPtr(blkList(1), solnData)

  if (isFirst == 1) then
     open(newunit=unit, file=trim(sim_outputFile), status="replace", action="write")
     write(unit, '(a)', advance="no") "# t[s] T[K]"
     do n = 1, NSPECIES
        write(unit, '(2a)', advance="no") " ", trim(sim_speciesName(n))
     end do
     write(unit, '(a)') ""
  else
     open(newunit=unit, file=trim(sim_outputFile), position="append", action="write")
  end if
  write(unit, '(*(es25.16e3, 1x))') simTime, temp, nden
  close(unit)

end subroutine IO_writeIntegralQuantities
