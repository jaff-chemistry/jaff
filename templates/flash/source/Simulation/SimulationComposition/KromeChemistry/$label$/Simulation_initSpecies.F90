! ABOUTME: Registers the Multispecies properties of the JAFF-generated network's species:
! ABOUTME: A = molar mass, Z = charge, and the adiabatic index of the network's EOS
!!****if* source/Simulation/SimulationComposition/KromeChemistry/Simulation_initSpecies
!!
!! NAME
!!  Simulation_initSpecies
!!
!! DESCRIPTION
!!  Sets A (molar mass [g mol^-1] = mass x Avogadro, as FLASH's EOS divides the
!!  ideal gas constant N_A k by it), Z (charge; a label: the electrons are their
!!  own species) and GAMMA (the adiabatic index of the network's EOS, so FLASH's
!!  multigamma EOS matches JAFF's) for every network species. Generated by jaffgen.
!!
!!***

subroutine Simulation_initSpecies()

  use Multispecies_interface, ONLY : Multispecies_setProperty
  use Simulation_interface, ONLY : Simulation_mapStrToInt
  use PhysicalConstants_interface, ONLY : PhysicalConstants_get

  implicit none

#include "constants.h"
#include "Flash.h"

#ifdef FLASH_MULTISPECIES
#include "Multispecies.h"

  integer :: n, isotope
  real :: avogadro
  character(len=16) :: names(NSPECIES)
  real :: masses(NSPECIES), charges(NSPECIES), gammas(NSPECIES)

  call PhysicalConstants_get("Avogadro", avogadro)

  $$JAFF REPEAT idx, specie_with_normalized_sign IN species_with_normalized_sign {
      SIGN { POS -> j  NEG -> k }
  }
  names($idx+1$) = "$specie_with_normalized_sign$"
  $$JAFF END
  $$JAFF REPEAT idx, specie_mass IN specie_masses
  masses($idx+1$) = $specie_mass$
  $$JAFF END
  $$JAFF REPEAT idx, specie_charge IN specie_charges
  charges($idx+1$) = $specie_charge$
  $$JAFF END
  $$JAFF REPEAT idx, specie_gamma IN specie_gammas
  gammas($idx+1$) = $specie_gamma$
  $$JAFF END

  do n = 1, NSPECIES
    call Simulation_mapStrToInt(trim(names(n)), isotope, MAPBLOCK_UNK)
    call Multispecies_setProperty(isotope, A, masses(n) * avogadro)
    call Multispecies_setProperty(isotope, Z, charges(n))
    call Multispecies_setProperty(isotope, GAMMA, gammas(n))
  end do

#endif

end subroutine Simulation_initSpecies
